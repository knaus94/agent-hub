export type MessageKey = keyof typeof ru;

type PluralBase<K> = K extends `${infer Base}.one` ? Base : never;
export type PluralKey = PluralBase<MessageKey>;

export const locale = 'ru';
const plurals = new Intl.PluralRules(locale);

export function t(key: MessageKey, vars: Record<string, string | number> = {}) {
   return ru[key].replace(/\{(\w+)\}/g, (_, name: string) => String(vars[name] ?? ''));
}

export function tp(key: PluralKey, count: number) {
   const form = plurals.select(count);
   const full = `${key}.${form}`;
   return t((full in ru ? full : `${key}.other`) as MessageKey, { count });
}
